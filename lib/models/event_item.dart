class EventItem {
  final String id;
  final String title;
  final String speaker;
  final String date;
  final String location;
  final String category;
  final String imageUrl;

  EventItem({
    required this.id,
    required this.title,
    required this.speaker,
    required this.date,
    required this.location,
    required this.category,
    required this.imageUrl,
  });
}